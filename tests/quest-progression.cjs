test('Granny Bramble offers the parcel after Seeds of Hope and pays the ingredients once', () => {
  const { q } = create(), D = q.data, S = q.S;
  const quest = D.QM.sunbloom_parcel;
  S.xp.fishing = D.XPF[35];
  S.xp.farming = D.XPF[5];
  S.unlocked.farming = true;
  S.q.seeds_of_hope = { s: 'done', p: [10] };
  assert.equal(q.questState(quest), 'locked', 'Grubnash still guards the road');
  S.towns.mossbarrow = { visited: true };
  S.town = 'mossbarrow';
  assert.equal(q.skillUnlocked('herbalism'), false, 'the quest can precede Herbalism');
  assert.equal(q.questState(quest), 'new');
  q.startQuest(quest.id);
  q.qev('harvest', 'potato', 6);
  assert.equal(q.objProg(quest, S.q[quest.id], 0), 0);
  q.give('seed_onion', 2);
  for (const plot of [0, 1]) assert.ok(q.plant(plot, 'onion'));
  q.simulate(75000);
  for (const plot of [0, 1]) assert.ok(q.harvest(plot));
  const onions = q.have('crop_onion');
  assert.ok(onions >= 6);
  assert.equal(q.questState(quest), 'ready');
  q.claimQuest(quest.id);
  q.claimQuest(quest.id);
  assert.equal(q.have('crop_onion'), onions + 10);
  assert.equal(q.have('crop_sunbloom'), 2);
  const save = q.validateSave(JSON.parse(JSON.stringify(S)));
  assert.equal(save.q[quest.id].s, 'done');
});
test('War Brewing opens in Tier I after Herbalism, with the original cost and Might effect', () => {
  const { q } = create(), D = q.data, S = q.S;
  const study = D.TECH.warbrew;
  const potion = D.POTION_RECIPES.find(recipe => recipe.id === 'potion_might');
  S.unlocked.research = S.unlocked.herbalism = true;
  S.coins = 7100;
  q.give('crop_onion', 10);
  q.give('crop_sunbloom', 2);
  q.give('bar_iron', 11);
  assert.equal(study.tier, 1);
  assert.equal(q.techReason(study), 'Needs Herbalism');
  assert.equal(q.canBrew(potion), false);
  assert.ok(q.startResearch('herbalism'));
  q.researchTick(15 * 60000);
  assert.ok(q.lvl('research') < 10, 'Tier II is still closed');
  assert.ok(q.startResearch('warbrew'));
  assert.equal(q.have('bar_iron'), 1);
  assert.equal(S.coins, 200);
  q.researchTick(44 * 60000);
  assert.equal(q.canBrew(potion), false);
  q.researchTick(60000);
  assert.equal(q.canBrew(potion), true);
  assert.ok(q.brew('potion_might'));
  assert.equal(q.have('potion_might'), 1);
  assert.equal(q.have('crop_sunbloom'), 0);
  assert.equal(q.have('bar_iron'), 0);
  assert.equal(D.ITEMS.potion_might.drink.mult, 1.15);
  assert.equal(D.ITEMS.potion_might.drink.mins, 20);
});
