/* Part C Task 25: at 1440 × 900 Home has no half-cut panel (everything fits); Welcome Back on a 6-hour returner keeps
   Continue on screen with its content in an inner scroll, at 1440 × 900 and 390 × 844; "Decide later" puts off every
   waiting encounter in one press, and each can still be opened from Activity. Granted fixture: fresh hero fishing, then
   6 simulated hours away; encounters generated by the real DQ.makeAwayEvents until three are waiting. */
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const path = require('node:path');
(async () => {
  const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined }); const errors = [];
  try {
    for (const [w, h] of [[1440, 900], [390, 844]]) {
      const p = await b.newPage({ viewport: { width: w, height: h } });
      p.on('pageerror', e => errors.push(e.message));
      await p.goto(process.env.IDLEWICK_URL || 'http://127.0.0.1:8765/');
      await p.locator('#t-new').click(); await p.locator('#cr-go').click();
      await p.waitForFunction(() => DQ.started && document.querySelector('#title').hidden);
      if (w === 1440) {
        await p.evaluate(() => { for (let i = 0; i < 12; i++) DQ.closeModal(); DQ.go('overview'); DQ.ui.render(true); });
        await p.waitForTimeout(600);
        const cut = await p.evaluate(() => [...document.querySelectorAll('#view .panel, #view [data-home-unit]')].filter(e => e.offsetWidth).map(e => { const r = e.getBoundingClientRect(); return { u: e.dataset.homeUnit || e.className, top: Math.round(r.top), bottom: Math.round(r.bottom) }; })
          .filter(r => r.top < innerHeight && r.bottom > innerHeight + 1));
        assert.deepEqual(cut, [], 'Home: no panel cut by the bottom of the window');
        if (process.env.SHOT_DIR) await p.screenshot({ path: path.join(process.env.SHOT_DIR, 'home-1440x900.png') });
      }
      const n = await p.evaluate(() => { const Q = DQ; for (let i = 0; i < 12; i++) Q.closeModal(); Q.paused = true;
        Q.startAct('fish', 'shrimp', { quiet: true }); const sum = Q.simulate(6 * 3600e3, 6 * 3600e3, { report: true });
        Q.S.inbox = Q.S.inbox || []; for (let i = 0; i < 12 && Q.S.inbox.length < 3; i++) Q.makeAwayEvents(sum, 6 * 3600e3);
        Q.emit('welcome', sum, 6 * 3600e3); return Q.S.inbox.length; });
      assert.ok(n >= 3, `three encounters waiting (${n})`);
      await p.waitForSelector('.welcome-digest .m-card');
      await p.waitForTimeout(500);
      const geo = await p.evaluate(() => { const t = [...document.querySelectorAll('#toastlayer .toast')].map(x => x.getBoundingClientRect()), a = document.querySelector('.welcome-digest .m-act').getBoundingClientRect(), toastOver = t.some(r => r.left < a.right && r.right > a.left && r.top < a.bottom && r.bottom > a.top); const c = document.querySelector('.welcome-digest .m-card').getBoundingClientRect(), body = document.querySelector('.welcome-digest .m-body'),
        cont = [...document.querySelectorAll('.welcome-digest .m-act button')].find(x => /Continue/.test(x.textContent)).getBoundingClientRect(),
        later = [...document.querySelectorAll('.welcome-digest .m-act button')].find(x => /Decide later/.test(x.textContent));
        return { toastOver, card: [c.top, c.bottom].map(Math.round), vh: innerHeight, cont: [cont.top, cont.bottom].map(Math.round), scroll: body.scrollHeight > body.clientHeight, later: !!later, bodyOverflow: getComputedStyle(body).overflowY }; });
      console.log(w, JSON.stringify(geo));
      assert.ok(geo.card[0] >= 0 && geo.card[1] <= geo.vh, 'modal fits the window');
      assert.ok(geo.cont[0] >= 0 && geo.cont[1] <= geo.vh, 'Continue visible without scrolling'); assert.equal(geo.toastOver, false, 'no toast over the footer');
      assert.equal(geo.bodyOverflow, 'auto', 'content scrolls inside the modal'); assert.ok(geo.later, 'Decide later offered');
      /* all content reachable: scroll the body to the end, Continue still in place */
      await p.evaluate(() => { const b = document.querySelector('.welcome-digest .m-body'); b.scrollTop = b.scrollHeight; });
      const contAfter = await p.evaluate(() => [...document.querySelectorAll('.welcome-digest .m-act button')].find(x => /Continue/.test(x.textContent)).getBoundingClientRect().bottom);
      assert.ok(contAfter <= h, 'Continue stays in view after scrolling');
      if (process.env.SHOT_DIR) await p.screenshot({ path: path.join(process.env.SHOT_DIR, `welcome-6h-${w}.png`) });
      const ids = await p.evaluate(() => DQ.S.inbox.map(e => String(e.id)));
      await p.locator('.welcome-digest .m-act button', { hasText: 'Decide later' }).click();
      await p.waitForTimeout(400);
      assert.equal(await p.locator('.welcome-digest').count(), 0, 'one press closes the return screen');
      const kept = await p.evaluate(() => DQ.S.inbox.map(e => String(e.id)));
      assert.deepEqual(kept, ids, 'every encounter kept, none expired or settled');
      for (const id of ids) {
        const opened = await p.evaluate(i => { DQ.go('activity'); DQ.ui.render(true); DQ.ui.DO.openevent(i); const ok = !!document.querySelector('.encounter-moment'); DQ.closeModal(); return ok; }, id);
        assert.ok(opened, `encounter ${id} still opens`);
      }
      await p.close();
    }
    assert.deepEqual(errors, []);
    console.log('viewport-fit-return: ok');
  } finally { await b.close(); }
})().catch(e => { console.error(e); process.exit(1); });
