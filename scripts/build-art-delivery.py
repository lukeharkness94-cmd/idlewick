"""Build delivery copies of the art completion pack for the game.

Reads docs/art-completion/manifest.json, writes compressed WebP atlases to assets/art-completion/web/
(the lossless PNG sources stay untouched) and js/art_completion_map.js with each entry's explicit
source rectangle. Run again whenever the pack or its manifest changes."""
from pathlib import Path
import json, sys
from PIL import Image

root = Path(__file__).resolve().parents[1]
manifest = json.loads((root / 'docs/art-completion/manifest.json').read_text())
out_dir = root / 'assets/art-completion/web'
out_dir.mkdir(parents=True, exist_ok=True)
force = '--force' in sys.argv
sheets = {}
for s in manifest['sets']:
    src = root / s['file']
    web = out_dir / (src.stem + '.webp')
    # re-encoding changes bytes, so existing delivery copies are kept; pass --force after replacing a source PNG
    if force or not web.exists():
        im = Image.open(src)
        if not s.get('transparent', True):
            im = im.convert('RGB')
        im.save(web, 'WEBP', quality=90, method=6)
    sheets[s['id']] = {
        'file': web.relative_to(root).as_posix(),
        'w': s['width'], 'h': s['height'],
        'e': {e['id']: e['rect'] for e in s['entries']},
        # optional placement of restoration pieces on a landscape: {x, base, h} as fractions of its width/height
        'p': {e['id']: e['place'] for e in s['entries'] if 'place' in e},
    }
    if 'target' in s:
        # fitted hero layers: the [x, y, w, h] box on the 384x576 hero canvas each crop is drawn into
        sheets[s['id']]['t'] = {e['id']: e.get('target', s['target']) for e in s['entries']}
    print(f"{s['id']}: {len(s['entries'])} entries, {web.stat().st_size // 1024} KB")
js = ('/* Generated by scripts/build-art-delivery.py from docs/art-completion/manifest.json. Do not edit by hand. */\n'
      'window.DQ.ART_COMPLETION = ' + json.dumps(sheets, separators=(',', ':')) + ';\n')
(root / 'js/art_completion_map.js').write_text(js)
print('wrote js/art_completion_map.js')
